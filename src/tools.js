/**
 * Utilities for safely diffing .env files, generating sanitized .env.example templates,
 * and producing Markdown documentation tables from envguard schemas.
 */

import { maskValue } from './parser.js';

const SENSITIVE_KEY_HINT = /(SECRET|TOKEN|PASSWORD|PASSWD|KEY|PRIVATE|CREDENTIAL|AUTH|DSN)/i;

/**
 * Compare two env value maps without revealing raw secret values by default.
 * @param {Record<string, string>} left
 * @param {Record<string, string>} right
 * @param {{ revealValues?: boolean }} [options]
 */
export function diffEnv(left, right, options = {}) {
  const reveal = Boolean(options.revealValues);
  const allKeys = [...new Set([...Object.keys(left), ...Object.keys(right)])].sort();

  /** @type {string[]} */
  const onlyInLeft = [];
  /** @type {string[]} */
  const onlyInRight = [];
  /** @type {Array<{ key: string, left: string, right: string }>} */
  const changed = [];
  /** @type {string[]} */
  const unchanged = [];

  for (const key of allKeys) {
    const inLeft = Object.prototype.hasOwnProperty.call(left, key);
    const inRight = Object.prototype.hasOwnProperty.call(right, key);

    if (inLeft && !inRight) {
      onlyInLeft.push(key);
    } else if (!inLeft && inRight) {
      onlyInRight.push(key);
    } else if (left[key] !== right[key]) {
      const sensitive = SENSITIVE_KEY_HINT.test(key);
      changed.push({
        key,
        left: reveal || !sensitive ? left[key] : maskValue(left[key]),
        right: reveal || !sensitive ? right[key] : maskValue(right[key])
      });
    } else {
      unchanged.push(key);
    }
  }

  return { onlyInLeft, onlyInRight, changed, unchanged };
}

/**
 * Generate a safe `.env.example` template from a real `.env` map and optional schema.
 * Sensitive values are replaced with clear placeholders.
 * @param {Record<string, string>} envValues
 * @param {{ variables?: Record<string, import('./validator.js').VariableRule> }} [schema]
 * @returns {string}
 */
export function generateExample(envValues, schema) {
  const lines = [
    '# Generated by envguard — do not commit real secrets to this file.',
    ''
  ];
  const schemaVars = schema?.variables || {};
  const keys = [...new Set([...Object.keys(schemaVars), ...Object.keys(envValues)])];

  for (const key of keys) {
    const rule = schemaVars[key];
    if (rule?.description) {
      lines.push(`# ${rule.description}`);
    }

    let exampleVal = '';
    if (rule?.example !== undefined) {
      exampleVal = String(rule.example);
    } else if (rule?.default !== undefined) {
      exampleVal = String(rule.default);
    } else if (rule?.secret || SENSITIVE_KEY_HINT.test(key)) {
      exampleVal = `your_${key.toLowerCase()}_here`;
    } else if (envValues[key] !== undefined) {
      exampleVal = envValues[key];
    }

    lines.push(`${key}=${exampleVal}`);
  }

  return lines.join('\n') + '\n';
}

/**
 * Generate a Markdown documentation table for all variables declared in a schema.
 * @param {{ title?: string, variables?: Record<string, import('./validator.js').VariableRule> }} schema
 * @returns {string}
 */
export function generateMarkdownDocs(schema) {
  const title = schema.title || 'Environment Variables';
  const vars = schema.variables || {};
  const lines = [
    `# ${title}`,
    '',
    '| Variable | Type | Required | Default | Description |',
    '| --- | --- | :---: | --- | --- |'
  ];

  for (const [key, rule] of Object.entries(vars)) {
    const typeLabel = rule.type === 'enum' && rule.enum
      ? `enum (${rule.enum.join(', ')})`
      : (rule.type || 'string');
    const reqLabel = rule.required ? 'Yes' : 'No';
    const defLabel = rule.default !== undefined ? `\`${rule.default}\`` : '—';
    const desc = (rule.description || '').replace(/\|/g, '\\|') || '—';
    const secretBadge = rule.secret ? ' *(secret)*' : '';
    lines.push(`| \`${key}\` | ${typeLabel} | ${reqLabel} | ${defLabel} | ${desc}${secretBadge} |`);
  }

  return lines.join('\n') + '\n';
}
